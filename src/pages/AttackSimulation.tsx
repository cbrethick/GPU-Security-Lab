type Tab = 'dictionary' | 'brute' | 'pattern';

/** Small, hardcoded demonstration list — not a real leaked wordlist. */
const DEMO_WORDLIST = [
  'password', 'admin', 'welcome', 'sunshine', 'dragon', 'monkey', 'letmein', 'football', 'shadow', 'master',
  'galaxy', 'pineapple', 'robot', 'nebula', 'orbit', 'falcon', 'quantum', 'matrix', 'cipher', 'phoenix',
  'tiger', 'coffee', 'rocket', 'silver', 'thunder', 'mango', 'cookie', 'banana', 'pixel', 'lantern',
];
/** Fictional secrets NOT in the list — shows that a dictionary attack can fail. */
const OUT_OF_LIST = ['velvet-cactus-orbit-91', 'Glacier!Harbor#Quartz', 'tundra-ember-sonar-lunar'];

interface Attempt { word: string; hash: string; match: boolean }

function DictionarySim() {
  const { settings } = useApp();
  const [target, setTarget] = useState<{ secret: string; hash: string; inList: boolean } | null>(null);
  const [attempts, setAttempts] = useState<Attempt[]>([]);
  const [running, setRunning] = useState(false);
  const [found, setFound] = useState<string | null>(null);
  const [revealed, setRevealed] = useState(false);
  const idx = useRef(0);

  const newTarget = async () => {
    const inList = Math.random() < 0.75;
    const pool = inList ? DEMO_WORDLIST : OUT_OF_LIST;
    const secret = pool[Math.floor(Math.random() * pool.length)];
    setTarget({ secret, hash: await hashText(secret, 'SHA-256'), inList });
    setAttempts([]); setFound(null); setRunning(false); setRevealed(false); idx.current = 0;
  };
  useEffect(() => { newTarget(); }, []); // eslint-disable-line react-hooks/exhaustive-deps

  useEffect(() => {
    if (!running || !target) return;
    if (idx.current >= DEMO_WORDLIST.length) { setRunning(false); return; }
    const t = setTimeout(async () => {
      const word = DEMO_WORDLIST[idx.current++];
      const hash = await hashText(word, 'SHA-256');
      const match = hash === target.hash;
      setAttempts((a) => [{ word, hash, match }, ...a]);
      if (match) { setFound(word); setRunning(false); }
      else if (idx.current >= DEMO_WORDLIST.length) setRunning(false);
    }, 260 / settings.simulationSpeed);
    return () => clearTimeout(t);
  }, [running, attempts.length, target, settings.simulationSpeed]);

  const exhausted = !found && idx.current >= DEMO_WORDLIST.length && attempts.length > 0;
  const progress = attempts.length / DEMO_WORDLIST.length;

  return (
    <div className="grid gap-4 lg:grid-cols-5">
      <Card glow className="lg:col-span-2">
        <CardTitle icon={<Target size={16} />} title="Fictional Target" subtitle="Generated by this app — a made-up lab account" />
        {target && (
          <div className="space-y-3 text-sm">
            <div className="rounded-lg border border-white/10 bg-ink-950/60 p-3">
              <p className="text-xs text-slate-500">Account</p><p className="mono text-slate-200">demo_user@lab.local</p>
              <p className="mt-2 text-xs text-slate-500">Stored hash (unsalted SHA-256 — a deliberately bad practice)</p>
              <p className="mono break-all text-xs text-accent">{target.hash}</p>
            </div>
            <div className="flex flex-wrap gap-2">
              {!running ? (
                <button className="btn-primary" onClick={() => setRunning(true)} disabled={!!found || exhausted}><Play size={15} /> {attempts.length ? 'Resume' : 'Start simulation'}</button>
              ) : <button className="btn-ghost" onClick={() => setRunning(false)}><Pause size={15} /> Pause</button>}
              <button className="btn-ghost" onClick={newTarget}><RefreshCw size={15} /> New target</button>
            </div>
            <div>
              <div className="mb-1 flex justify-between text-xs text-slate-400"><span>Candidates checked</span><span className="mono">{attempts.length} / {DEMO_WORDLIST.length}</span></div>
              <div className="h-2 overflow-hidden rounded-full bg-white/5"><motion.div className="h-full rounded-full bg-accent" animate={{ width: `${progress * 100}%` }} /></div>
            </div>
            <AnimatePresence>
              {found && (
                <motion.div initial={{ opacity: 0, y: 6 }} animate={{ opacity: 1, y: 0 }} className="rounded-lg border border-rose-500/40 bg-rose-500/10 p-3">
                  <p className="flex items-center gap-2 font-semibold text-rose-200"><CheckCircle2 size={16} /> Match after {attempts.length} guesses</p>
                  <p className="mt-1 text-xs text-rose-100/80">The fictional password was the common word "<span className="mono">{found}</span>". Common words fall immediately, and unsalted fast hashes let one guess test every account at once.</p>
                </motion.div>
              )}
              {exhausted && (
                <motion.div initial={{ opacity: 0, y: 6 }} animate={{ opacity: 1, y: 0 }} className="rounded-lg border border-emerald-500/40 bg-emerald-500/10 p-3">
                  <p className="flex items-center gap-2 font-semibold text-emerald-200"><XCircle size={16} /> Word list exhausted — no match</p>
                  <p className="mt-1 text-xs text-emerald-100/80">The secret wasn't a dictionary word. {revealed ? <>It was "<span className="mono">{target.secret}</span>" — a long random passphrase.</> : <button className="underline" onClick={() => setRevealed(true)}>Reveal the fictional secret</button>}</p>
                </motion.div>
              )}
            </AnimatePresence>
            <SafetyNote>Only a {DEMO_WORDLIST.length}-word built-in list is used against a hash this app generated. No external hashes or wordlists can be loaded.</SafetyNote>
          </div>
        )}
      </Card>
      <Card className="lg:col-span-3">
        <CardTitle icon={<BookOpen size={16} />} title="Candidate Log" subtitle="Each candidate is hashed and compared with the stored hash" />
        <div className="max-h-[420px] space-y-1.5 overflow-y-auto pr-1">
          {attempts.length === 0 && <p className="py-12 text-center text-sm text-slate-500">Press “Start simulation” to begin checking candidates.</p>}
          <AnimatePresence initial={false}>
            {attempts.map((a) => (
              <motion.div key={a.word} initial={{ opacity: 0, x: -10 }} animate={{ opacity: 1, x: 0 }}
                className={`flex items-center gap-3 rounded-lg border px-3 py-2 text-xs ${a.match ? 'border-rose-500/50 bg-rose-500/10' : 'border-white/5 bg-ink-950/40'}`}>
                {a.match ? <CheckCircle2 size={14} className="shrink-0 text-rose-300" /> : <XCircle size={14} className="shrink-0 text-slate-600" />}
                <span className="mono w-24 shrink-0 text-slate-200">{a.word}</span>
                <span className="mono truncate text-slate-500">{a.hash}</span>
                <span className={`ml-auto shrink-0 ${a.match ? 'text-rose-300' : 'text-slate-600'}`}>{a.match ? 'MATCH' : 'no match'}</span>
              </motion.div>
            ))}
          </AnimatePresence>
        </div>
      </Card>
    </div>
  );
}

const CHARSETS = [
  { value: 10, label: 'Digits (10)' },
  { value: 26, label: 'Lowercase (26)' },
  { value: 62, label: 'Alphanumeric (62)' },
  { value: 95, label: 'Printable ASCII (95)' },
];
const RATES = [
  { label: 'Simulated CPU (lab model)', rate: 120_000 },
  { label: 'Simulated GPU (lab model)', rate: 1_850_000 },
  { label: 'Illustrative high-end GPU · MD5', rate: 1e11 },
  { label: 'Illustrative high-end GPU · bcrypt (cost 12)', rate: 1.5e3 },
];

function BruteForceViz() {
  const [charset, setCharset] = useState(62);
  const [length, setLength] = useState(8);
  const total = Math.pow(charset, length);
  const chart = useMemo(() => Array.from({ length: 20 }, (_, i) => {
    const L = i + 1;
    return { L, 'Digits': L * Math.log10(10), 'Lowercase': L * Math.log10(26), 'Alphanumeric': L * Math.log10(62), 'Printable': L * Math.log10(95) };
  }), []);
  const series = [
    { key: 'Digits', color: SERIES.c4 }, { key: 'Lowercase', color: SERIES.c3 }, { key: 'Alphanumeric', color: SERIES.cpu }, { key: 'Printable', color: SERIES.gpu },
  ];

  return (
    <div className="grid gap-4 lg:grid-cols-5">
      <Card glow className="lg:col-span-2">
        <CardTitle icon={<Calculator size={16} />} title="Search Space Calculator" subtitle="Math only — no passwords are generated or tested" />
        <div className="space-y-5">
          <div>
            <p className="label">Character set</p>
            <Segmented size="sm" value={charset} onChange={setCharset} options={CHARSETS.map((c) => ({ value: c.value, label: c.label }))} />
            <div className="mt-3"><Slider label="Custom character-set size" value={charset} min={2} max={128} onChange={setCharset} /></div>
          </div>
          <Slider label="Password length" value={length} min={1} max={24} onChange={setLength} />
          <div className="rounded-xl border border-accent/30 bg-accent/5 p-4">
            <p className="text-xs text-slate-400">Total possibilities = Character Set Size <sup>Password Length</sup></p>
            <p className="mono mt-2 text-lg text-white">{charset}<sup>{length}</sup> = <span className="neon-text">{fmtBig(total)}</span></p>
            <p className="mono mt-1 text-xs text-slate-500">≈ 10^{(length * Math.log10(charset)).toFixed(1)} · {(length * Math.log2(charset)).toFixed(1)} bits</p>
          </div>
        </div>
      </Card>
      <Card className="lg:col-span-3">
        <CardTitle title="Time to exhaust the full search space" subtitle="Worst case; average is half. Rates are simulated or illustrative." />
        <ul className="space-y-3">
          {RATES.map((r) => {
            const s = total / r.rate;
            const pct = Math.min(100, Math.max(2, (Math.log10(s + 1) / 20) * 100));
            return (
              <li key={r.label}>
                <div className="flex items-center justify-between gap-3 text-xs"><span className="text-slate-300">{r.label} <span className="mono text-slate-500">({fmtCompact(r.rate)}/s)</span></span><span className="mono text-right text-accent">{fmtDuration(s)}</span></div>
                <div className="mt-1 h-1.5 overflow-hidden rounded-full bg-white/5"><motion.div className="h-full rounded-full" style={{ background: s < 86400 ? '#e11d48' : s < 31_557_600 * 100 ? '#d97706' : '#059669' }} animate={{ width: `${pct}%` }} /></div>
              </li>
            );
          })}
        </ul>
        <div className="mt-5 flex items-center justify-between"><p className="text-xs font-medium text-slate-300">Search-space growth (log₁₀ possibilities)</p><Legend items={series.map((s) => ({ label: s.key, color: s.color }))} /></div>
        <div className="mt-2 h-52">
          <ResponsiveContainer>
            <LineChart data={chart} margin={{ top: 8, right: 12, left: 0, bottom: 0 }}>
              <CartesianGrid stroke={GRID} vertical={false} />
              <XAxis dataKey="L" stroke={AXIS} tick={{ fontSize: 11 }} tickLine={false} axisLine={false} label={{ value: 'length', position: 'insideBottomRight', offset: -2, fill: AXIS, fontSize: 10 }} />
              <YAxis stroke={AXIS} tick={{ fontSize: 11 }} tickFormatter={(v) => `10^${Math.round(v)}`} tickLine={false} axisLine={false} width={48} />
              <Tooltip content={<ChartTooltip formatter={(v) => `10^${v.toFixed(1)}`} />} labelFormatter={(l) => `Length ${l}`} />
              {series.map((s) => <Line key={s.key} type="monotone" dataKey={s.key} stroke={s.color} strokeWidth={2} dot={false} activeDot={{ r: 4 }} />)}
            </LineChart>
          </ResponsiveContainer>
        </div>
        <p className="mt-2 text-[11px] text-slate-500">Each extra character multiplies the space by the charset size — length grows security exponentially.</p>
      </Card>
    </div>
  );
}

const FICTIONAL_NAMES = ['Arjun', 'Priya', 'Kavin', 'Meera', 'Rohan', 'Divya', 'Nila', 'Vikram'];
const WORDS = ['tiger', 'mango', 'rocket', 'coffee', 'silver', 'galaxy', 'cookie', 'falcon'];
const pick = <T,>(a: T[]) => a[Math.floor(Math.random() * a.length)];
const cap = (s: string) => s[0].toUpperCase() + s.slice(1);

const PATTERNS = [
  { name: 'Word + Number', gen: () => `${pick(WORDS)}${Math.floor(Math.random() * 1000)}`, guesses: 10_000 * 1_000, model: '10K common words × 1,000 numbers', why: 'People append short numbers to a word to satisfy “must contain a digit” rules.' },
  { name: 'Name + Year', gen: () => `${pick(FICTIONAL_NAMES)}${1980 + Math.floor(Math.random() * 30)}`, guesses: 5_000 * 2 * 100, model: '5K names × 2 cases × 100 years', why: 'Names and birth/graduation years are personal, easy to remember, and easy to research.' },
  { name: 'Capitalized Word + Symbol', gen: () => `${cap(pick(WORDS))}${pick(['!', '@', '#', '$'])}${Math.random() < 0.5 ? Math.floor(Math.random() * 10) : ''}`, guesses: 10_000 * 33 * 11, model: '10K words × 33 symbols × 11 digit options', why: 'Capital first + symbol last is the most common way people satisfy complexity rules.' },
  { name: 'Repeated Characters', gen: () => { const c = pick(['a', '1', 'x', '7', 'z']); return c.repeat(6 + Math.floor(Math.random() * 5)); }, guesses: 95 * 20, model: '95 characters × 20 lengths', why: 'A repeated character has almost no entropy no matter how long it is.' },
  { name: 'Keyboard Walk', gen: () => pick(['qwerty123', 'asdfgh', '1qaz2wsx', 'zxcvbnm', 'qwertyuiop']), guesses: 5_000, model: '≈ 5K known keyboard paths', why: 'Adjacent-key paths look random but are among the first candidates tried.' },
];

function PatternDemo() {
  const [examples, setExamples] = useState(() => PATTERNS.map((p) => p.gen()));
  const regen = () => setExamples(PATTERNS.map((p) => p.gen()));
  const data = PATTERNS.map((p, i) => {
    const len = examples[i].length;
    return { name: p.name.replace('Capitalized', 'Cap.'), pattern: Math.log10(p.guesses), brute: len * Math.log10(95), patternRaw: p.guesses, bruteRaw: Math.pow(95, len) };
  });

  return (
    <div className="space-y-4">
      <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-3">
        {PATTERNS.map((p, i) => (
          <Card key={p.name} delay={i * 0.04}>
            <div className="flex items-center justify-between"><h3 className="font-semibold text-white">{p.name}</h3><Badge tone={p.guesses < 1e6 ? 'critical' : 'warning'}>{p.guesses < 1e6 ? 'Critical' : 'High risk'}</Badge></div>
            <p className="mono mt-3 rounded-lg border border-white/10 bg-ink-950/60 px-3 py-2 text-sm text-accent">{examples[i]}</p>
            <p className="mt-1 text-[10px] text-slate-500">Synthetic example</p>
            <p className="mt-3 text-sm text-slate-400">{p.why}</p>
            <div className="mt-3 grid grid-cols-2 gap-2 text-xs">
              <div className="rounded-lg bg-rose-500/10 p-2"><p className="text-slate-400">Pattern-aware guesses</p><p className="mono text-rose-200">{fmtBig(p.guesses)}</p><p className="text-[10px] text-slate-500">{p.model}</p></div>
              <div className="rounded-lg bg-emerald-500/10 p-2"><p className="text-slate-400">Naive brute force ({examples[i].length} chars)</p><p className="mono text-emerald-200">{fmtBig(Math.pow(95, examples[i].length))}</p><p className="text-[10px] text-slate-500">95^{examples[i].length}</p></div>
            </div>
            <p className="mt-2 text-xs text-slate-400">At the simulated GPU rate (1.85M/s): <span className="mono text-rose-300">{fmtDuration(p.guesses / 1_850_000)}</span></p>
          </Card>
        ))}
        <Card className="flex flex-col justify-center">
          <p className="text-sm text-slate-300">Patterns shrink the real search space by many orders of magnitude, because attackers model how humans choose passwords instead of trying every combination.</p>
          <button className="btn-primary mt-4" onClick={regen}><Shuffle size={15} /> Generate new synthetic examples</button>
        </Card>
      </div>
      <Card>
        <CardTitle title="Pattern-aware vs naive search space" subtitle="log₁₀ guesses needed for the examples above — the gap is why predictable patterns are dangerous" right={<Legend items={[{ label: 'Pattern-aware', color: SERIES.c3 }, { label: 'Naive brute force', color: SERIES.c5 }]} />} />
        <div className="h-64">
          <ResponsiveContainer>
            <BarChart data={data} barGap={2} margin={{ top: 8, right: 8, left: 0, bottom: 0 }}>
              <CartesianGrid stroke={GRID} vertical={false} />
              <XAxis dataKey="name" stroke={AXIS} tick={{ fontSize: 10 }} tickLine={false} axisLine={false} interval={0} />
              <YAxis stroke={AXIS} tick={{ fontSize: 11 }} tickFormatter={(v) => `10^${v}`} tickLine={false} axisLine={false} width={48} />
              <Tooltip cursor={{ fill: 'rgba(255,255,255,0.03)' }} content={<ChartTooltip formatter={(v) => `10^${v.toFixed(1)}`} />} />
              <Bar dataKey="pattern" name="Pattern-aware" fill={SERIES.c3} radius={[4, 4, 0, 0]} maxBarSize={30} />
              <Bar dataKey="brute" name="Naive brute force" fill={SERIES.c5} radius={[4, 4, 0, 0]} maxBarSize={30} />
            </BarChart>
          </ResponsiveContainer>
        </div>
      </Card>
    </div>
  );
}

